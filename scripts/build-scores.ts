/**
 * Turn the short notation files content/pieces/<slug>.notes into MusicXML (content/pieces/<slug>.musicxml).
 *
 *   npm run scores:build            # all .notes files
 *   npm run scores:build -- lightly-row
 *
 * A piece can also come straight from MuseScore (just the .musicxml, no .notes); this script only helps writing
 * simple guitar pieces by hand. Every bar is checked against the time signature. Format: see content/pieces/README.md.
 * The parser and the MusicXML writer live in src/lib/score/ (the teacher's score editor uses the same writer).
 */
import fs from "node:fs";
import path from "node:path";
import { toMusicXml } from "../src/lib/score/musicxml";
import { parseNotes } from "../src/lib/score/notes";

const DIR = path.join(process.cwd(), "content", "pieces");

function build(slug: string) {
  const meta = JSON.parse(fs.readFileSync(path.join(DIR, `${slug}.json`), "utf8")) as { title: string; composer?: string; sourceNote?: string };
  const { time, tempo, key, parts } = parseNotes(fs.readFileSync(path.join(DIR, `${slug}.notes`), "utf8"), `${slug}.notes`);
  const xml = toMusicXml(
    {
      title: meta.title,
      composer: meta.composer,
      time,
      tempo,
      key,
      parts,
      software: "Harmoni Gitar build-scores",
      comments: [
        `Generated by scripts/build-scores.ts from ${slug}.notes. Edit the .notes file, or edit this file in MuseScore and delete the .notes file.`,
        ...(meta.sourceNote ? [meta.sourceNote] : []),
      ],
    },
    `${slug}.notes`,
  );
  fs.writeFileSync(path.join(DIR, `${slug}.musicxml`), xml);
  return { bars: parts[0].voices[0].length, parts: parts.length };
}

const only = process.argv.slice(2);
const slugs = (only.length ? only : fs.readdirSync(DIR).filter((f) => f.endsWith(".notes")).map((f) => f.replace(/\.notes$/, ""))).sort();
let failed = false;
for (const slug of slugs) {
  try {
    const r = build(slug);
    console.log(`${slug}: ${r.bars} birama, ${r.parts} part`);
  } catch (e) {
    failed = true;
    console.error(e instanceof Error ? e.message : e);
  }
}
if (failed) process.exit(1);
